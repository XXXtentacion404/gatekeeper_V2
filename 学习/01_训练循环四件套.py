"""
第 1 课 · 训练循环四件套
=====================================================================
这一课不学新理论，只干一件事：把"训练"用代码跑一遍，看清楚这四样东西各干什么。

    ① Dataset        —— 我手上有什么数据（输入 + 正确答案）
    ② nn.Module      —— 网络长什么样（一个参数可调的函数）
    ③ loss.backward()—— 算出每个参数该往哪边调、调多少
    ④ optimizer.step()—— 真的去调

【练什么】直接拿项目里的场景：人在往闸口走，脚底的纵坐标是随帧号单调变化的。
    我们只给网络一堆 (帧号, 脚底纵坐标) 的数据点，
    让它自己把 y = k*x + b 里的 k 和 b 找出来。

    真实规律（我们心里知道，但故意不告诉网络）： y = 0.30 + 0.50 * x
    x = 帧号 / 100          （0 ~ 1，第几帧占总时长的比例）
    y = 脚底纵坐标 / 图像高度（0 ~ 1，脚底在画面高度的百分之几）

    这里为什么要先除以尺度（归一化）？—— 因为像素数值太大（0~720），
    梯度也会跟着巨大，学习率稍大就飞了。你自己项目里 letterbox 缩放、
    RKNN 输入量化，本质都是同一件事：把数值压到小范围再喂给网络。

【跑法】在本文件所在目录执行：
    D:\\Software\\Anaconda3\\envs\\yolov8\\python.exe 01_训练循环四件套.py
"""

import torch
import torch.nn as nn

torch.manual_seed(0)          # 固定随机种子：保证每次跑出来的初始参数一模一样，方便对照


# =====================================================================
# ① Dataset —— 我有什么数据
# =====================================================================
# 真要做项目时，这里换成你自己的 Dataset 类（从磁盘读 ROI 图、配对背景/当前图）。
# 现在先用现造的数据，把训练循环本身看清楚。

x = torch.linspace(0.0, 1.0, 200).unsqueeze(1)   # 200 个样本，每个样本 1 个特征
y = 0.30 + 0.50 * x                              # 正确答案（标签）

print("=" * 66)
print("① 数据")
print("   x.shape =", tuple(x.shape), "  （200 个样本，每样本 1 个数）")
print("   y.shape =", tuple(y.shape))
print("   前 3 个样本:", x[:3].flatten().tolist())
print("   对应标签  :", y[:3].flatten().tolist())


# =====================================================================
# ② nn.Module —— 网络长什么样
# =====================================================================
# nn.Linear(1, 1) 就是它自己：out = weight * in + bias，里面就 2 个可训练参数。
# 我们的整个"网络"现在就长这样 —— 一个可调函数。

class LineNet(nn.Module):
    def __init__(self):
        super().__init__()          # 固定写法，别问，先照抄
        self.fc = nn.Linear(1, 1)   # 1 个输入 -> 1 个输出

    def forward(self, x):
        return self.fc(x)           # 前向：输入进来，输出出去


model = LineNet()
print()
print("=" * 66)
print("② 网络")
print("   结构: Linear(1 -> 1)  共",
      sum(p.numel() for p in model.parameters()), "个可训练参数")
print("   初始 k(weight) =", f"{model.fc.weight.item():+.4f}   <-- 随机数，不是我们要的")
print("   初始 b(bias)   =", f"{model.fc.bias.item():+.4f}   <-- 随机数，不是我们要的")
print("   目标: k -> +0.5000, b -> +0.3000")


# =====================================================================
# ③④ 损失 + 反向传播 + 更新  —— 训练循环
# =====================================================================

loss_fn = nn.MSELoss()                              # 损失：均方误差，"差多少"
optimizer = torch.optim.SGD(model.parameters(),     # 优化器：负责调参数
                            lr=0.5)                 # lr = 学习率 = 每次调的步长

print()
print("=" * 66)
print("③④ 训练循环")
print(f"{'epoch':>6} {'loss':>10} {'k(weight)':>12} {'b(bias)':>12}")
print("-" * 66)

for epoch in range(0, 301):

    pred = model(x)              # ---- 前向：算出预测 ----
    loss = loss_fn(pred, y)      # ---- 算损失：预测和真值差多少 ----

    optimizer.zero_grad()        # ---- 清空上一轮攒下的梯度（不清就会累加！）----
    loss.backward()              # ---- ③ 反向传播：算出 k、b 各自的梯度 ----
    optimizer.step()             # ---- ④ 更新参数：param -= lr * grad ----

    if epoch % 50 == 0:
        print(f"{epoch:>6} {loss.item():>10.6f} "
              f"{model.fc.weight.item():>+12.4f} {model.fc.bias.item():>+12.4f}")

print("-" * 66)
print("训练结束后的参数:")
print("   k(weight) =", f"{model.fc.weight.item():+.4f}", "  (目标 +0.5000)")
print("   b(bias)   =", f"{model.fc.bias.item():+.4f}", "  (目标 +0.3000)")
print()
print("-> 网络从一堆随机数出发，只看数据，自己把 k 和 b 逼到了正确值。")
print("   这就是'训练'的全部：前向 -> 损失 -> 反向 -> 更新，重复很多次。")


